"""Testhilfen im Entwicklermodus: Ressourcen, Rekord, Startwelle, schillernder Gegner, Leistungsmessung. Ohne Entwicklermodus unsichtbar und wirkungslos."""
import os,sys
HERE=os.path.dirname(os.path.abspath(__file__))
GAME='file://'+os.path.join(os.path.dirname(HERE),'dist','web','index.html')
os.makedirs(os.path.join(HERE,'out'),exist_ok=True);os.chdir(os.path.join(HERE,'out'))
from playwright.sync_api import sync_playwright
def check(ok,msg):
    print(('ok   ' if ok else 'Traceback FEHLER ')+msg)
hid=lambda pg,s:pg.evaluate("s=>document.querySelector(s).hidden",s)
with sync_playwright() as p:
    b=p.chromium.launch();pg=b.new_page(viewport={'width':390,'height':844},device_scale_factor=2,has_touch=True)
    errs=[];pg.on('pageerror',lambda e: errs.append('PAGEERR '+str(e)))
    pg.goto(GAME);pg.wait_for_timeout(300);pg.click('#bSet');pg.wait_for_timeout(150)
    check(hid(pg,'#bDev') and hid(pg,'#perf'),'ohne Entwicklermodus: Knopf „Testhilfen“ und Messanzeige versteckt')
    check(pg.evaluate("()=>{save.devStart=40;const w=stats(save).startWave;save.devStart=0;return w}")==1,'ohne Entwicklermodus wirkt die Test-Startwelle nicht')
    pg.evaluate("()=>{save.dev=true;persist()}");pg.reload();pg.wait_for_timeout(300);pg.click('#bSet');pg.wait_for_timeout(150)
    check(not hid(pg,'#bDev'),'mit Entwicklermodus: Knopf „Testhilfen“ sichtbar')
    pg.click('#bDev');pg.wait_for_timeout(150)
    pg.click('[data-dc="s"][data-op="m"]');pg.click('[data-dc="k"][data-op="k"]');pg.click('[data-dc="p"][data-op="x"]');pg.click('[data-dc="q"][data-op="k"]')
    cur=pg.evaluate("()=>[save.cur.s,save.cur.k,save.cur.p,save.q]")
    check(cur==[1000000,1000,100,1000],'Ressourcen gesetzt: '+str(cur))
    pg.click('[data-dc="k"][data-op="0"]');check(pg.evaluate("()=>save.cur.k")==0,'Ressource auf 0')
    pg.click('[data-db="25"]');pg.click('[data-db="5"]');check(pg.evaluate("()=>save.best")==30,'Rekordwelle 30')
    for i in range(4):pg.click('[data-ds="10"]')
    check(pg.evaluate("()=>stats(save).startWave")==41,'Startwelle 41: '+str(pg.evaluate("()=>stats(save).startWave")))
    check(pg.evaluate("()=>document.querySelector('#dev .mbox').scrollWidth<=document.querySelector('#dev .mbox').clientWidth+1"),'Testhilfen passen in die Breite')
    pg.screenshot(path='th1_testhilfen.png')
    pg.click('[data-ds="0"]');check(pg.evaluate("()=>stats(save).startWave")==1,'Startwelle wieder normal')
    pg.click('[data-dt="devShiny"]');pg.click('[data-dt="devPerf"]');pg.wait_for_timeout(100)
    check(not hid(pg,'#perf'),'Messanzeige sichtbar')
    pg.click('#bDevClose');pg.click('#bSetClose');pg.wait_for_timeout(100)
    check('1,00M' in pg.inner_text('#hubCur'),'Hub zeigt die neuen Splitter: '+pg.inner_text('#hubCur').replace('\n',' '))
    check(pg.evaluate("()=>JSON.parse(localStorage.getItem(Store.key)).cur.s")==1000000,'Änderungen sind gespeichert')
    pg.click('#bStart');pg.wait_for_timeout(4000)
    check(pg.evaluate("()=>run.en.some(e=>e.shiny)||Object.keys(run.killsBy).some(k=>k.startsWith('shiny:'))"),'schillernder Gegner in Welle 1')
    rep=pg.evaluate("()=>Perf.report()")
    check('Bilder' in rep and 'Ruckler' in rep and pg.evaluate("()=>Perf.fr.length")>100,'Messung zählt Bilder: '+rep.split('\n')[3])
    check('Bilder/s' in pg.inner_text('#perf'),'Messanzeige läuft: '+pg.inner_text('#perf').replace('\n',' | '))
    pg.evaluate("()=>{const a=performance.now();while(performance.now()-a<80);}");pg.wait_for_timeout(300)
    check(pg.evaluate("()=>Perf.hit.length")>=1,'ein künstlicher Hänger wird als Ruckler erfasst')
    pg.screenshot(path='th2_messung.png')
    pg.evaluate("()=>{save.dev=false}")
    check(pg.evaluate("()=>{save.devStart=40;return stats(save).startWave}")==1,'nach Beenden des Entwicklermodus keine Wirkung mehr')
    print('\n'.join(errs) or 'no errors');b.close()
