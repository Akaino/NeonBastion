// Bosse: alle 10 Wellen einer, alle TWIN_EVERY2 Wellen zwei von gegenüberliegenden Seiten mit je TWIN_HP2 des Bosslebens.
// Sie kommen ohne Begleitwelle und schicken alle BOSS2_SEND Sekunden abwechselnd Kanonenfutter und Saboteure vor.
export const TWIN_EVERY2 = 25,
  TWIN_HP2 = 0.75,
  BOSS2_SEND = 5;
export const bossFodder = w => Math.min(12, 4 + Math.floor(w / 10)); // Schwärmer je Schub
export const bossSabos = w => Math.min(4, 1 + Math.floor(w / 20)); // Saboteure je Schub

export const waveShare2 = (t, w) => {
  const T = ETYPES2[t];
  return w >= T.from ? Math.min(T.max, T.step * (w - T.from + 1)) : 0;
};

/* Feste Welle (Vorgabe des Nutzers: Anzahl, Typen und Richtung stehen je Welle fest, nichts davon ist Zufall).
   Liefert { w, boss, twin, list: [{ type, elite, twin? }], dirs: [Winkel …], types: { Typ: Anzahl } }. */
export function wave2(w) {
  const twin = w % TWIN_EVERY2 === 0,
    boss = twin || w % 10 === 0,
    a1 = (((w * 137.508) % 360) * Math.PI) / 180, // goldener Winkel: verteilt die Richtungen gleichmäßig, ohne Muster
    dirs = [a1];
  let list = [];
  if (boss) {
    list.push({ type: 'boss', elite: false });
    if (twin) {
      list.push({ type: 'boss', elite: false, twin: true });
      dirs.push(a1 + Math.PI);
    }
  } else {
    const n = Math.round(Math.min(7 + w * 2.3, 55 + w * 0.7)),
      sh = WAVE_MIX2.map(t => [t, waveShare2(t, w)]),
      sum = sh.reduce((a, x) => a + x[1], 0),
      k = sum > MIX_MAX2 ? MIX_MAX2 / sum : 1,
      slots = [];
    let rest = n;
    sh.forEach(([t, s], ti) => {
      const c = Math.min(rest, Math.round(n * s * k));
      rest -= c;
      // gleichmäßig über die Welle verteilen; der kleine Versatz je Typ legt die Reihenfolge bei Gleichstand fest
      for (let i = 0; i < c; i++) slots.push([(i + 0.5) / c + ti * 1e-4, t]);
    });
    for (let i = 0; i < rest; i++) slots.push([(i + 0.5) / rest, 'swarm']);
    slots.sort((a, b) => a[0] - b[0]);
    const every = Math.round(1 / Math.min(0.08, 0.03 + 0.003 * w)); // jeder so vielte Gegner ist Elite
    list = slots.map(([, type], i) => ({ type, elite: i % every === every - 1 }));
    if (w >= 12 && w % 3 === 0) dirs.push(a1 + ((120 + ((w * 53) % 120)) * Math.PI) / 180); // jede dritte Welle ab 12 aus zwei Richtungen
  }
  const types = {};
  for (const x of list) types[x.type] = (types[x.type] || 0) + 1;
  return { w, boss, twin, list, dirs, types };
}
