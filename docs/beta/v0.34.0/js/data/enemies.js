export const waveMix = w => {
  const m = WAVE_MIX.map(t => [t, waveShare(t, w)]),
    sum = m.reduce((a, x) => a + x[1], 0),
    k = sum > MIX_MAX ? MIX_MAX / sum : 1;
  return m.map(([t, s]) => [t, s * k]);
};
